use serde::Deserialize;
use std::collections::{btree_map::Entry, BTreeMap, BTreeSet};

use super::shared::{entity_path, label_short_name};
use super::EntityKey;
use crate::{ErrorBuilder, ErrorCategory, ValidationResult};

/// Raw architecture JSON read by the validator, generated by the
/// `dependable_element` Bazel rule.
///
/// Maps full Bazel labels to target entries. Converted into a matching index
/// by [`Self::to_bazel_architecture`].
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct BazelInput {
    pub components: BTreeMap<String, BazelInputEntry>,
}

/// JSON entry for one target: its own required design name and optional lists
/// of directly contained units and components.
///
/// The target's full Bazel label is the key in [`BazelInput::components`].
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct BazelInputEntry {
    pub design_name: String,
    #[serde(default)]
    pub units: Vec<BazelEntityRef>,
    #[serde(default)]
    pub components: Vec<BazelEntityRef>,
}

/// Reference to a directly contained unit or component.
#[derive(Debug, Deserialize, Clone)]
#[serde(deny_unknown_fields)]
pub struct BazelEntityRef {
    /// Full Bazel target label, used to look up component entries and report errors.
    pub label: String,
    /// Design name used with the full parent path for PlantUML matching.
    pub design_name: String,
}

/// Architecture matching index built from [`BazelInput`] by
/// [`BazelInput::to_bazel_architecture`], not the raw JSON format.
///
/// Map keys contain the lowercased design name and optional full parent design
/// path. Map values retain the original Bazel labels.
#[derive(Clone, Default)]
pub struct BazelArchitecture {
    /// Top-level dependable elements (`<<SEooC>>`), keyed with `parent = None`.
    pub seooc_set: BTreeMap<EntityKey, String>,
    /// Nested components (`<<component>>`), keyed with the full parent design path.
    pub comp_set: BTreeMap<EntityKey, String>,
    /// Units (`<<unit>>`), keyed with the full parent design path.
    pub unit_set: BTreeMap<EntityKey, String>,
    /// Design paths that cannot be reliably matched due to conflicting names or
    /// missing entries; matching skips them and descendants.
    pub unmatchable_paths: BTreeSet<String>,
}

impl BazelInput {
    /// Build a [`BazelArchitecture`] index from this architecture JSON.
    ///
    /// A pre-pass collects the **full** label of every nested component,
    /// so only an exact label match marks a component as nested -
    /// a top-level component is never treated as nested just because another
    /// target in a different package shares the same short name.
    ///
    /// Children are matched by their full parent design path.
    /// Component containment is assumed acyclic, as enforced by Bazel.
    /// Exactly one root is required; otherwise errors are recorded and an empty
    /// index is returned.
    pub fn to_bazel_architecture(&self, result: &mut ValidationResult) -> BazelArchitecture {
        let mut architecture = BazelArchitecture::default();
        let roots = self.collect_roots(result);

        // Defend against malformed generated input, normal Bazel output has exactly one root.
        if roots.is_empty() {
            result
                .add_failure("Bazel architecture has no top-level dependable element.".to_string());
            return architecture;
        }
        if roots.len() > 1 {
            let mut error = ErrorBuilder::new(ErrorCategory::Design)
                .title("Bazel architecture must have exactly one top-level dependable element")
                .field("root count", roots.len().to_string());
            for (index, (label, _)) in roots.iter().enumerate() {
                error = error.field(format!("bazel label {}", index + 1), *label);
            }
            result.add_failure(
                error
                    .fix("keep exactly one top-level dependable element in the Bazel architecture input")
                    .build(),
            );
            return architecture;
        }

        let (label, entry) = roots[0];
        let name = entry.design_name.to_lowercase();
        architecture
            .seooc_set
            .insert((name.clone(), None), label.to_string());
        self.index_children(label, &name, &mut architecture, result);

        architecture
    }

    fn collect_roots(&self, result: &mut ValidationResult) -> Vec<(&str, &BazelInputEntry)> {
        let nested_component_labels: BTreeSet<String> = self
            .components
            .values()
            .flat_map(|entry| entry.components.iter())
            .map(|component| component.label.clone())
            .collect();

        let mut roots = Vec::new();
        for (label, entry) in &self.components {
            if let Err(msg) = label_short_name(label) {
                result.add_failure(msg);
                continue;
            }
            entry.validate_children(label, result);
            if nested_component_labels.contains(label) {
                continue;
            }
            roots.push((label.as_str(), entry));
        }

        roots
    }

    fn index_children(
        &self,
        label: &str,
        path: &str,
        architecture: &mut BazelArchitecture,
        result: &mut ValidationResult,
    ) {
        let Some(entry) = self.components.get(label) else {
            result.add_failure(format!(
                "Bazel component {label} referenced at design path \"{path}\" has no architecture entry."
            ));
            architecture.unmatchable_paths.insert(path.to_string());
            return;
        };
        // Index all direct children first so sibling name conflicts are known before recursion.
        for (children, set, is_component) in [
            (&entry.units, &mut architecture.unit_set, false),
            (&entry.components, &mut architecture.comp_set, true),
        ] {
            for child in children {
                if label_short_name(&child.label).is_err() {
                    continue;
                }
                let key = (child.design_name.to_lowercase(), Some(path.to_string()));
                match set.entry(key) {
                    Entry::Vacant(entry) => {
                        entry.insert(child.label.clone());
                    }
                    Entry::Occupied(entry) => {
                        if is_component {
                            architecture
                                .unmatchable_paths
                                .insert(entity_path(entry.key()));
                        }
                    }
                }
            }
        }
        // Expand only non-conflicting component paths to avoid cascading descendant errors.
        for child in &entry.components {
            if label_short_name(&child.label).is_err() {
                continue;
            }
            let child_path = format!("{path}.{}", child.design_name.to_lowercase());
            if !architecture.unmatchable_paths.contains(&child_path) {
                self.index_children(&child.label, &child_path, architecture, result);
            }
        }
    }
}

impl BazelInputEntry {
    fn validate_children(&self, parent: &str, result: &mut ValidationResult) {
        for (kind, children) in [("unit", &self.units), ("component", &self.components)] {
            let mut names = BTreeMap::new();
            for child in children {
                if let Err(msg) = label_short_name(&child.label) {
                    result.add_failure(msg);
                    continue;
                }
                let name = child.design_name.to_lowercase();
                if let Some(previous) = names.insert(name.clone(), &child.label) {
                    result.add_failure(duplicate_bazel_entity_error(
                        kind,
                        &name,
                        parent,
                        previous,
                        &child.label,
                    ));
                }
            }
        }
    }
}

impl BazelArchitecture {
    pub(crate) fn is_unmatchable(&self, key: &EntityKey) -> bool {
        let path = entity_path(key);
        self.unmatchable_paths.iter().any(|unmatchable| {
            path == *unmatchable
                || path
                    .strip_prefix(unmatchable)
                    .is_some_and(|suffix| suffix.starts_with('.'))
        })
    }
}

fn duplicate_bazel_entity_error(
    kind: &str,
    name: &str,
    parent: &str,
    first_label: &str,
    second_label: &str,
) -> String {
    ErrorBuilder::new(ErrorCategory::Design)
        .title(format!(
            "{kind} \"{name}\" is defined more than once in Bazel."
        ))
        .field("name", format!("\"{name}\""))
        .field("parent", parent)
        .field("first bazel label", first_label)
        .field("second bazel label", second_label)
        .fix(format!(
            "keep only one Bazel {kind} definition for \"{name}\" under \"{parent}\", or give one of the duplicates a distinct design_name"
        ))
        .build()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn entity_ref(label: &str) -> BazelEntityRef {
        BazelEntityRef {
            label: label.to_string(),
            design_name: label_short_name(label).unwrap_or(label).to_string(),
        }
    }

    fn make_arch(entries: Vec<(&str, Vec<&str>, Vec<&str>)>) -> BazelInput {
        let mut components = BTreeMap::new();
        for (label, units, nested) in entries {
            components.insert(
                label.to_string(),
                BazelInputEntry {
                    design_name: label_short_name(label).unwrap_or(label).to_string(),
                    units: units.into_iter().map(entity_ref).collect(),
                    components: nested.into_iter().map(entity_ref).collect(),
                },
            );
        }
        BazelInput { components }
    }

    #[test]
    fn rejects_entry_without_design_name() {
        let error = serde_json::from_str::<BazelInput>(
            r#"{"components": {"@//pkg:component_target": {}}}"#,
        )
        .unwrap_err();

        assert!(error.to_string().contains("missing field `design_name`"));
    }

    #[test]
    fn root_detection_preserves_label_case() {
        for (root, component) in [("@//:Root", "@//:root"), ("@//:root", "@//:Root")] {
            let arch = make_arch(vec![
                (root, vec![], vec![component]),
                (component, vec!["@//:worker"], vec![]),
            ]);
            let mut result = ValidationResult::default();
            let architecture = arch.to_bazel_architecture(&mut result);

            assert!(result.is_empty(), "{:?}", result.failures);
            assert_eq!(architecture.seooc_set.len(), 1);
            assert_eq!(architecture.comp_set.len(), 1);
            assert_eq!(architecture.unit_set.len(), 1);
            assert_eq!(
                architecture.seooc_set.get(&("root".to_string(), None)),
                Some(&root.to_string()),
            );
            assert_eq!(
                architecture
                    .comp_set
                    .get(&("root".to_string(), Some("root".to_string()))),
                Some(&component.to_string()),
            );
            assert_eq!(
                architecture
                    .unit_set
                    .get(&("worker".to_string(), Some("root.root".to_string()))),
                Some(&"@//:worker".to_string()),
            );
        }
    }

    #[test]
    fn uses_entry_design_name_for_parent_key() {
        let arch: BazelInput = serde_json::from_str(
            r#"{
                "components": {
                    "@//pkg:seooc_target": {
                        "design_name": "Seooc_Design",
                        "components": [{
                            "label": "@//pkg:component_target",
                            "design_name": "Component_Design"
                        }]
                    },
                    "@//pkg:component_target": {
                        "design_name": "Component_Design",
                        "units": [{
                            "label": "@//pkg:unit_target",
                            "design_name": "Unit_Design"
                        }]
                    }
                }
            }"#,
        )
        .unwrap();
        let mut result = ValidationResult::default();
        let architecture = arch.to_bazel_architecture(&mut result);

        assert!(result.is_empty(), "{:?}", result.failures);
        assert!(architecture
            .seooc_set
            .contains_key(&("seooc_design".to_string(), None)));
        assert!(architecture.comp_set.contains_key(&(
            "component_design".to_string(),
            Some("seooc_design".to_string()),
        )));
        assert!(architecture.unit_set.contains_key(&(
            "unit_design".to_string(),
            Some("seooc_design.component_design".to_string()),
        )));
    }

    #[test]
    fn duplicate_component_paths_are_not_expanded() {
        let arch: BazelInput = serde_json::from_str(
            r#"{"components": {
                "@//:seooc": {
                    "design_name": "seooc",
                    "components": [
                        {"label": "@//:x_for_A", "design_name": "component_x"},
                        {"label": "@//:x_for_B", "design_name": "component_x"},
                        {"label": "@//:valid", "design_name": "valid"}
                    ]
                },
                "@//:x_for_A": {
                    "design_name": "component_x",
                    "units": [{"label": "@//:unit_target", "design_name": "unit_1"}]
                },
                "@//:x_for_B": {
                    "design_name": "component_x",
                    "units": [{"label": "@//:unit_target", "design_name": "unit_1"}]
                },
                "@//:valid": {
                    "design_name": "valid",
                    "units": [{"label": "@//:worker", "design_name": "worker"}]
                }
            }}"#,
        )
        .unwrap();
        let mut result = ValidationResult::default();
        let architecture = arch.to_bazel_architecture(&mut result);

        assert_eq!(result.failures.len(), 1, "{:?}", result.failures);
        assert!(result.failures[0].contains("Component \"component_x\""));
        assert_eq!(architecture.unmatchable_paths.len(), 1);
        assert!(architecture.unmatchable_paths.contains("seooc.component_x"));
        assert!(architecture
            .is_unmatchable(&("unit_1".to_string(), Some("seooc.component_x".to_string()),)));
        assert!(!architecture.is_unmatchable(&("valid".to_string(), Some("seooc".to_string()),)));
        assert!(!architecture
            .unit_set
            .contains_key(&("unit_1".to_string(), Some("seooc.component_x".to_string()),)));
        assert_eq!(architecture.unit_set.len(), 1);
        assert_eq!(
            architecture
                .unit_set
                .get(&("worker".to_string(), Some("seooc.valid".to_string()))),
            Some(&"@//:worker".to_string()),
        );
    }

    #[test]
    fn duplicate_units_under_one_actual_parent_are_rejected() {
        for second_label in ["@//:unit_1", "@//other:unit_1"] {
            let arch = make_arch(vec![
                ("@//:seooc", vec![], vec!["@//:comp"]),
                ("@//:comp", vec!["@//:unit_1", second_label], vec![]),
            ]);
            let mut result = ValidationResult::default();
            arch.to_bazel_architecture(&mut result);

            assert_eq!(result.failures.len(), 1, "{:?}", result.failures);
            assert!(result.failures[0].contains("Unit \"unit_1\""));
            assert!(result.failures[0].contains("@//:comp"));
        }
    }

    #[test]
    fn missing_component_entry_is_reported_without_skipping_valid_siblings() {
        let arch = make_arch(vec![
            ("@//:seooc", vec![], vec!["@//:missing", "@//:valid"]),
            ("@//:valid", vec!["@//:worker"], vec![]),
        ]);
        let mut result = ValidationResult::default();
        let architecture = arch.to_bazel_architecture(&mut result);

        assert_eq!(result.failures.len(), 1, "{:?}", result.failures);
        assert!(result.failures[0].contains("@//:missing"));
        assert!(result.failures[0].contains("seooc.missing"));
        assert!(result.failures[0].contains("has no architecture entry"));
        assert!(architecture.is_unmatchable(&("missing".to_string(), Some("seooc".to_string()),)));
        assert!(
            architecture.is_unmatchable(&("child".to_string(), Some("seooc.missing".to_string()),))
        );
        assert_eq!(
            architecture
                .unit_set
                .get(&("worker".to_string(), Some("seooc.valid".to_string()),)),
            Some(&"@//:worker".to_string()),
        );
    }

    #[test]
    fn shared_component_is_indexed_under_each_parent_path() {
        let arch = make_arch(vec![
            ("@//:seooc", vec![], vec!["@//:parent_a", "@//:parent_b"]),
            ("@//:parent_a", vec![], vec!["@//:shared"]),
            ("@//:parent_b", vec![], vec!["@//:shared"]),
            ("@//:shared", vec!["@//:worker"], vec![]),
        ]);
        let mut result = ValidationResult::default();
        let architecture = arch.to_bazel_architecture(&mut result);

        assert!(result.is_empty(), "{:?}", result.failures);
        assert_eq!(architecture.seooc_set.len(), 1);
        assert_eq!(architecture.comp_set.len(), 4);
        assert_eq!(architecture.unit_set.len(), 2);
        for parent in ["seooc.parent_a", "seooc.parent_b"] {
            assert_eq!(
                architecture
                    .comp_set
                    .get(&("shared".to_string(), Some(parent.to_string()))),
                Some(&"@//:shared".to_string()),
            );
            assert_eq!(
                architecture
                    .unit_set
                    .get(&("worker".to_string(), Some(format!("{parent}.shared")),)),
                Some(&"@//:worker".to_string()),
            );
        }
    }

    #[test]
    fn multiple_roots_are_rejected_without_indexing_children() {
        for second_root in ["@//pkg_b:root", "@//pkg_b:other_root"] {
            let arch = make_arch(vec![
                ("@//pkg_a:root", vec!["@//:worker_a"], vec![]),
                (second_root, vec!["@//:worker_b"], vec![]),
            ]);
            let mut result = ValidationResult::default();
            let architecture = arch.to_bazel_architecture(&mut result);

            assert_eq!(result.failures.len(), 1, "{:?}", result.failures);
            assert!(result.failures[0].contains("exactly one top-level dependable element"));
            assert!(architecture.seooc_set.is_empty());
            assert!(architecture.unit_set.is_empty());
            assert!(architecture.comp_set.is_empty());
        }
    }

    #[test]
    fn missing_root_is_rejected() {
        let arch = make_arch(vec![]);
        let mut result = ValidationResult::default();
        let architecture = arch.to_bazel_architecture(&mut result);

        assert_eq!(result.failures.len(), 1, "{:?}", result.failures);
        assert!(result.failures[0].contains("no top-level dependable element"));
        assert!(architecture.seooc_set.is_empty());
        assert!(architecture.comp_set.is_empty());
        assert!(architecture.unit_set.is_empty());
    }
}
