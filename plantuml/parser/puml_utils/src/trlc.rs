//! Writer for generated TRLC files: one package of records of a single model.

use std::collections::BTreeSet;

/// Value of a record field.
pub enum TrlcValue {
    /// String literal.
    Text(String),
    Integer(u64),
    /// Qualified record name `Package.Name`; its package is imported.
    Reference(String),
    List(Vec<TrlcValue>),
}

impl TrlcValue {
    /// The TRLC text of the value; the package of a reference is added to `imports`.
    fn render<'a>(&'a self, imports: &mut BTreeSet<&'a str>) -> String {
        match self {
            Self::Text(text) => trlc_string_literal(text),
            Self::Integer(value) => value.to_string(),
            Self::Reference(name) => {
                imports.extend(package_of(name));
                name.clone()
            }
            Self::List(values) => {
                let values: Vec<String> = values.iter().map(|v| v.render(imports)).collect();
                format!("[{}]", values.join(", "))
            }
        }
    }
}

/// One record of a generated file.
pub struct TrlcRecord {
    /// Qualified type, e.g. `ScoreReq.ApiMethod`; its package is imported.
    pub record_type: String,
    pub name: String,
    /// Where the record comes from (`<diagram>:<line>`), emitted as a comment.
    pub origin: String,
    pub fields: Vec<(&'static str, TrlcValue)>,
}

/// Renders `records` as the TRLC file of `package`. The imports follow from the
/// record types and references, so a file without records imports nothing
/// (TRLC flags unused imports).
pub fn render_trlc_file(generated_from: &str, package: &str, records: &[TrlcRecord]) -> String {
    let mut imports: BTreeSet<&str> = BTreeSet::new();
    let mut body = String::new();
    for record in records {
        imports.extend(package_of(&record.record_type));
        body.push_str(&format!("// {}\n", record.origin));
        body.push_str(&format!("{} {} {{\n", record.record_type, record.name));
        for (field, value) in &record.fields {
            body.push_str(&format!("  {field} = {}\n", value.render(&mut imports)));
        }
        body.push_str("}\n\n");
    }

    let mut out = format!("// GENERATED by puml_cli from {generated_from} -- do not edit\n");
    out.push_str(&format!("package {package}\n\n"));
    for imported in &imports {
        out.push_str(&format!("import {imported}\n"));
    }
    if !imports.is_empty() {
        out.push('\n');
    }
    out.push_str(&body);
    out
}

/// Whether `name` is a plain TRLC identifier: an ASCII letter followed by
/// letters, digits and `_`. Keywords are not checked.
pub fn is_trlc_identifier(name: &str) -> bool {
    name.chars().next().is_some_and(|c| c.is_ascii_alphabetic())
        && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
}

fn package_of(qualified: &str) -> Option<&str> {
    qualified.rsplit_once('.').map(|(package, _)| package)
}

/// Escape a Rust string as a TRLC string literal (including the surrounding
/// quotes).
fn trlc_string_literal(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            _ => out.push(c),
        }
    }
    out.push('"');
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn record(name: &str, fields: Vec<(&'static str, TrlcValue)>) -> TrlcRecord {
        TrlcRecord {
            record_type: "Model.Kind".to_string(),
            name: name.to_string(),
            origin: "d.puml:3".to_string(),
            fields,
        }
    }

    #[test]
    fn quotes_backslashes_and_newlines_are_escaped() {
        assert_eq!(trlc_string_literal("a\"b\\c\nd"), "\"a\\\"b\\\\c\\nd\"");
    }

    #[test]
    fn file_without_records_has_no_imports() {
        assert_eq!(
            render_trlc_file("things", "Pkg", &[]),
            "// GENERATED by puml_cli from things -- do not edit\npackage Pkg\n\n"
        );
    }

    #[test]
    fn records_render_fields_in_order() {
        let records = [record(
            "R",
            vec![
                ("title", TrlcValue::Text("a \"b\"".to_string())),
                ("line", TrlcValue::Integer(7)),
                (
                    "items",
                    TrlcValue::List(vec![
                        TrlcValue::Text("x".to_string()),
                        TrlcValue::Text("y".to_string()),
                    ]),
                ),
            ],
        )];

        assert_eq!(
            render_trlc_file("things", "Pkg", &records),
            "// GENERATED by puml_cli from things -- do not edit\n\
             package Pkg\n\
             \n\
             import Model\n\
             \n\
             // d.puml:3\n\
             Model.Kind R {\n\
             \x20 title = \"a \\\"b\\\"\"\n\
             \x20 line = 7\n\
             \x20 items = [\"x\", \"y\"]\n\
             }\n\
             \n"
        );
    }

    #[test]
    fn imports_cover_record_types_and_references_sorted_once() {
        let records = [
            record(
                "A",
                vec![(
                    "refs",
                    TrlcValue::List(vec![
                        TrlcValue::Reference("Lib.A".to_string()),
                        TrlcValue::Reference("Lib.B".to_string()),
                        TrlcValue::Reference("Other.C".to_string()),
                    ]),
                )],
            ),
            record(
                "B",
                vec![("ref", TrlcValue::Reference("Lib.D".to_string()))],
            ),
        ];

        let out = render_trlc_file("things", "Pkg", &records);

        assert!(
            out.contains("package Pkg\n\nimport Lib\nimport Model\nimport Other\n\n"),
            "got: {out}"
        );
        assert!(out.contains("refs = [Lib.A, Lib.B, Other.C]"), "got: {out}");
    }

    #[test]
    fn identifiers_start_with_a_letter() {
        assert!(is_trlc_identifier("a_B1"));
        assert!(!is_trlc_identifier(""));
        assert!(!is_trlc_identifier("_a"));
        assert!(!is_trlc_identifier("1a"));
        assert!(!is_trlc_identifier("a-b"));
        assert!(!is_trlc_identifier("a.b"));
    }
}
