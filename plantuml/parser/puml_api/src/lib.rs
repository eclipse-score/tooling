//! Public API items of resolved class diagrams, rendered as `ScoreReq.ApiMethod`
//! TRLC records (`public_api.trlc`, see [`render_trlc`]).
//!
//! One record is generated per public method name of an entity (all overloads
//! collapsed into one record, one signature each) and per free function. The
//! record name is `<entity id, '.' -> '_'>_<method>`; free functions use their
//! namespace instead of the entity id (`Free_<name>` without a namespace).
//! Operators and destructors are named by an operator table / `destructor`.
//! Constructors and destructors are items like any other public method.
//! Record names are compared like TRLC does (ignoring case and `_`); two items
//! mapping to the same name are an error.
//!
//! The `const` qualifier is not part of a signature yet: const and non-const
//! overloads of a method render identically and are merged.

mod collector;
mod naming;
mod signature;

pub use collector::ApiCollector;
use puml_utils::{render_trlc_file, TrlcRecord, TrlcValue};

/// One generated `ApiMethod` record.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ApiMethod {
    /// TRLC record name.
    pub name: String,
    /// Declared signatures, one per overload, in diagram order.
    pub signatures: Vec<String>,
    /// Source diagram of the first declaration.
    pub diagram: String,
    /// Line of the first declaration.
    pub line: u32,
}

#[derive(Debug, thiserror::Error, PartialEq, Eq)]
pub enum ApiError {
    #[error(
        "{origin}: `{part}` cannot be part of a TRLC record name; only letters, digits and `_` \
         are allowed and the name must start with a letter"
    )]
    InvalidName { origin: String, part: String },
    #[error("{origin}: operator `{operator}` has no TRLC record name")]
    UnsupportedOperator { origin: String, operator: String },
    #[error(
        "`{first}` ({first_location}) and `{second}` ({second_location}) both map to the TRLC \
         record name `{record}`; record names are compared ignoring case and `_`"
    )]
    NameCollision {
        record: String,
        first: String,
        first_location: String,
        second: String,
        second_location: String,
    },
}

/// Renders `methods` as one TRLC file of `ScoreReq.ApiMethod` records in
/// `package`. Every record carries a `<diagram>:<line>` comment pointing back
/// at its source declaration. Each signature is wrapped in backticks: reports
/// join the signatures of a record with `, `, which signatures contain too.
pub fn render_trlc(package: &str, methods: &[ApiMethod]) -> String {
    let records: Vec<TrlcRecord> = methods
        .iter()
        .map(|method| TrlcRecord {
            record_type: "ScoreReq.ApiMethod".to_string(),
            name: method.name.clone(),
            origin: format!("{}:{}", method.diagram, method.line),
            fields: vec![
                ("diagram", TrlcValue::Text(method.diagram.clone())),
                ("line", TrlcValue::Integer(u64::from(method.line))),
                (
                    "signatures",
                    TrlcValue::List(
                        method
                            .signatures
                            .iter()
                            .map(|s| TrlcValue::Text(format!("`{s}`")))
                            .collect(),
                    ),
                ),
            ],
        })
        .collect();
    render_trlc_file("public API class diagrams", package, &records)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn render_emits_one_record_per_item() {
        let items = vec![ApiMethod {
            name: "A_f".to_string(),
            signatures: vec!["void A::f()".to_string(), "void A::f(\"x\")".to_string()],
            diagram: "pkg/d.puml".to_string(),
            line: 14,
        }];

        assert_eq!(
            render_trlc("Pkg_api", &items),
            "// GENERATED by puml_cli from public API class diagrams -- do not edit\n\
             package Pkg_api\n\
             \n\
             import ScoreReq\n\
             \n\
             // pkg/d.puml:14\n\
             ScoreReq.ApiMethod A_f {\n\
             \x20 diagram = \"pkg/d.puml\"\n\
             \x20 line = 14\n\
             \x20 signatures = [\"`void A::f()`\", \"`void A::f(\\\"x\\\")`\"]\n\
             }\n\
             \n"
        );
    }

    #[test]
    fn render_without_items_has_no_import() {
        assert_eq!(
            render_trlc("Pkg_api", &[]),
            "// GENERATED by puml_cli from public API class diagrams -- do not edit\n\
             package Pkg_api\n\
             \n"
        );
    }
}
