"""Tests for relocate_lobster_items."""

import os
import sys
import tempfile
import unittest
from unittest import mock

from lobster.common.errors import Message_Handler
from lobster.common.io import lobster_read, lobster_write
from lobster.common.items import Requirement, Tracing_Tag
from lobster.common.location import File_Reference

import relocate_lobster_items
from relocate_lobster_items import relocate_items

# As `puml_utils::render_trlc_file` writes it.
_GENERATED = """\
// GENERATED by puml_cli from FTA diagrams -- do not edit
package Pkg_fta

import ScoreReq
import FailureModes

// first_fta.puml:12
ScoreReq.RootCause First {
  title = "First"
  diagram = "first_fta.puml"
  line = 12
  failure_modes = [FailureModes.Fm]
}

// second_fta.puml:30
ScoreReq.RootCause Second {
  title = "Second"
  diagram = "second_fta.puml"
  line = 30
  failure_modes = [FailureModes.Fm]
}
"""

_SOURCES = {"first_fta.puml": "pkg/first_fta.puml", "second_fta.puml": "pkg/second_fta.puml"}


def _record_line(generated: str, name: str) -> int:
    for number, text in enumerate(generated.splitlines(), start=1):
        if text.startswith(f"ScoreReq.RootCause {name} "):
            return number
    raise AssertionError(name)


def _req(name: str, location: File_Reference) -> Requirement:
    return Requirement(
        tag=Tracing_Tag("req", f"Pkg_fta.{name}"),
        location=location,
        framework="TRLC",
        kind="RootCause",
        name=f"Pkg_fta.{name}",
        text=name,
    )


class TestRelocateItems(unittest.TestCase):
    """Tests for relocate_items."""

    def setUp(self) -> None:
        directory = tempfile.TemporaryDirectory()
        self.addCleanup(directory.cleanup)
        self.directory = directory.name
        self.generated_path = os.path.join(self.directory, "bin", "pkg", "fta_events.trlc")
        self._write_generated(_GENERATED)

    def _write_generated(self, text: str) -> None:
        os.makedirs(os.path.dirname(self.generated_path), exist_ok=True)
        with open(self.generated_path, "w", encoding="utf-8") as f:
            f.write(text)

    def _write(self, items: list[Requirement]) -> str:
        path = os.path.join(self.directory, "items.lobster")
        with open(path, "w", encoding="utf-8") as f:
            lobster_write(f, Requirement, "test", items)
        return path

    def _in_generated(self, name: str, filename: str | None = None) -> Requirement:
        location = File_Reference(filename or self.generated_path, _record_line(_GENERATED, name), 20)
        return _req(name, location)

    def _relocate(self, items: list[Requirement], sources: dict[str, str] = _SOURCES) -> list[Requirement]:
        return relocate_items(self._write(items), self.generated_path, sources)

    def test_items_of_the_generated_file_move_to_their_diagram_and_line(self) -> None:
        items = self._relocate([self._in_generated("First"), self._in_generated("Second")])
        self.assertEqual(
            [item.location.to_string() for item in items], ["pkg/first_fta.puml:12", "pkg/second_fta.puml:30"]
        )

    def test_items_located_elsewhere_are_kept(self) -> None:
        elsewhere = _req("Other", File_Reference("pkg/failure_modes.trlc", 3, 5))
        items = self._relocate([self._in_generated("First"), elsewhere])
        self.assertEqual(
            [item.location.to_string() for item in items], ["pkg/first_fta.puml:12", "pkg/failure_modes.trlc:3:5"]
        )

    def test_only_the_location_changes(self) -> None:
        original = self._in_generated("First")
        expected = {key: value for key, value in original.to_json().items() if key != "location"}
        relocated = self._relocate([original])[0]
        self.assertEqual({key: value for key, value in relocated.to_json().items() if key != "location"}, expected)

    def test_generated_file_is_matched_by_its_normalized_path(self) -> None:
        unnormalized = os.path.join(self.directory, "bin", ".", "pkg", "..", "pkg", "fta_events.trlc")
        items = self._relocate([self._in_generated("First", filename=unnormalized)])
        self.assertEqual(items[0].location.to_string(), "pkg/first_fta.puml:12")

    def test_diagram_is_looked_up_by_the_name_of_its_origin_comment(self) -> None:
        # The API generator names a diagram of an external repository by its short path.
        self._write_generated(_GENERATED.replace("// first_fta.puml:12", "// ../repo+/score/api/first_fta.puml:12"))
        sources = {"../repo+/score/api/first_fta.puml": "external/repo+/score/api/first_fta.puml"}
        items = self._relocate([self._in_generated("First")], sources)
        self.assertEqual(items[0].location.to_string(), "external/repo+/score/api/first_fta.puml:12")

    def test_unknown_line_leaves_the_location_without_a_line(self) -> None:
        self._write_generated(_GENERATED.replace("// first_fta.puml:12", "// first_fta.puml:0"))
        items = self._relocate([self._in_generated("First")])
        self.assertEqual(items[0].location.to_string(), "pkg/first_fta.puml")

    def test_diagram_without_a_source_is_an_error(self) -> None:
        with self.assertRaises(SystemExit) as ctx:
            self._relocate([self._in_generated("First")], {"second_fta.puml": "pkg/second_fta.puml"})
        self.assertIn("originates from 'first_fta.puml'", str(ctx.exception))

    def test_record_without_an_origin_comment_is_an_error(self) -> None:
        without_comment = _GENERATED.replace("// first_fta.puml:12\n", "")
        self._write_generated(without_comment)
        item = _req("First", File_Reference(self.generated_path, _record_line(without_comment, "First"), 20))
        with self.assertRaises(SystemExit) as ctx:
            self._relocate([item])
        self.assertIn("no record with an origin comment", str(ctx.exception))

    def test_unreadable_file_is_reported(self) -> None:
        with self.assertRaises(SystemExit) as ctx:
            relocate_items("/nonexistent/items.lobster", self.generated_path, _SOURCES)
        self.assertIn("Failed to parse lobster file", str(ctx.exception))

    def test_main_writes_the_relocated_items(self) -> None:
        output = os.path.join(self.directory, "out", "relocated.lobster")
        argv = [
            "relocate_lobster_items",
            "--input-lobster",
            self._write([self._in_generated("First"), self._in_generated("Second")]),
            "--generated-trlc",
            self.generated_path,
            *[arg for name, path in _SOURCES.items() for arg in ("--source", f"{name}={path}")],
            "--output",
            output,
        ]
        with mock.patch.object(sys, "argv", argv):
            relocate_lobster_items.main()
        written: dict[str, Requirement] = {}
        lobster_read(Message_Handler(), output, "test", written)
        self.assertEqual(
            {str(key): item.location.to_string() for key, item in written.items()},
            {"req Pkg_fta.First": "pkg/first_fta.puml:12", "req Pkg_fta.Second": "pkg/second_fta.puml:30"},
        )


if __name__ == "__main__":
    unittest.main()
