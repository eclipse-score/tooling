"""Convert a Sphinx-Needs FMEA and its fault trees to LOBSTER items.

Counterpart of ``failure_modes``, ``fault_trees`` and ``safety_analysis``
without TRLC. It writes the same three LOBSTER files, so
``dependability_analysis`` and ``dependable_element`` check them unchanged:

* ``failuremodes.lobster``: one ``FailureMode`` item ``req <package>.<need ID>``
  per ``comp_saf_fmea`` need that violates ``--arch-id``. A violated
  ``real_arc_int_op`` need becomes a reference to the public API method whose
  signature declares ``<interface title>::<operation title>(``.
* ``fta_root_causes.lobster``: one ``RootCause`` item per root cause of the
  ``fta_events.trlc`` stub generated by ``puml_cli`` from the fault trees,
  referencing the failure modes named by the ``$FailureMode`` macros.
* ``assessments.lobster``: a need rated ``sufficient: yes`` assesses the root
  causes of its failure mode; the item references them and the ``mitigated_by``
  measures that are items of ``--measures``.

The references are not checked here: LOBSTER reports a fault tree naming an
unknown failure mode, and an operation without a matching API method, as
unknown tracing targets. Only the ``fault_id`` values are checked, against the
fault models documented on the ``Guideword`` enum of the TRLC model (``--spec``).
"""

from __future__ import annotations

import argparse
import logging
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from lobster.common.errors import LOBSTER_Error, Message_Handler
from lobster.common.io import lobster_read, lobster_write
from lobster.common.items import Requirement, Tracing_Tag
from lobster.common.location import File_Reference
from lobster_sphinx_needs import ConfigError, _location, _text_values, load_needs, parse_link

GENERATOR = "safety_analysis_spn"
FRAMEWORK = "Sphinx-Needs"
NEED_TYPE = "comp_saf_fmea"

logger = logging.getLogger(__name__)

_LEVEL_MAP = {
    "error": logging.ERROR,
    "warn": logging.WARNING,
    "info": logging.INFO,
    "debug": logging.DEBUG,
}

_RE_IDENTIFIER = re.compile(r"^[A-Za-z][A-Za-z0-9_]*$")
_RE_GUIDEWORD_ENUM = re.compile(r"\benum\s+Guideword\b[^{]*\{(?P<body>.*?)\n\}", re.DOTALL)
_RE_FAULT_ID_COMMENT = re.compile(r"^\s*//\s*(?P<id>[A-Z]{2}_\d{2}_\d{2})\s*:", re.MULTILINE)
_RE_STUB_PACKAGE = re.compile(r"^package\s+(?P<name>\w+)", re.MULTILINE)
_RE_STUB_ROOT_CAUSE = re.compile(
    r"^ScoreReq\.RootCause\s+(?P<name>\w+)\s*\{\n(?P<body>.*?)\n\}", re.MULTILINE | re.DOTALL
)
_RE_STUB_FIELD = re.compile(r"^\s*(?P<field>\w+)\s*=\s*(?P<value>.*)$", re.MULTILINE)
_RE_STUB_STRING = re.compile(r'^"((?:[^"\\]|\\.)*)"$')
_RE_RST_SPECIAL = re.compile(r"([\\*`|_])")


class ConversionError(Exception):
    """The FMEA needs or the fault-tree stub cannot be converted."""


@dataclass(frozen=True)
class RootCause:
    name: str
    title: str
    diagram: str
    line: int
    failure_modes: tuple[str, ...]


def load_fault_ids(spec_files: list[str]) -> set[str]:
    """Fault model IDs documented on the ``Guideword`` enum of the TRLC model."""
    for path in spec_files:
        enum = _RE_GUIDEWORD_ENUM.search(Path(path).read_text(encoding="utf-8"))
        if enum:
            fault_ids = set(_RE_FAULT_ID_COMMENT.findall(enum.group("body")))
            if fault_ids:
                return fault_ids
    raise ConversionError(f"no Guideword enum with fault model IDs in {', '.join(spec_files)}")


def _unescape(literal: str, path: str) -> str:
    match = _RE_STUB_STRING.match(literal.strip())
    if not match:
        raise ConversionError(f"{path}: expected a string literal, got {literal!r}")
    return re.sub(r"\\(.)", lambda m: "\n" if m.group(1) == "n" else m.group(1), match.group(1))


def load_root_causes(path: str) -> tuple[str, list[RootCause]]:
    """Package and ``RootCause`` records of an ``fta_events.trlc`` stub generated by ``puml_cli``."""
    text = Path(path).read_text(encoding="utf-8")
    package = _RE_STUB_PACKAGE.search(text)
    if not package:
        raise ConversionError(f"{path}: no package declaration")
    root_causes = []
    for record in _RE_STUB_ROOT_CAUSE.finditer(text):
        fields = {m.group("field"): m.group("value") for m in _RE_STUB_FIELD.finditer(record.group("body"))}
        failure_modes = fields.get("failure_modes", "").strip().strip("[]")
        root_causes.append(
            RootCause(
                name=record.group("name"),
                title=_unescape(fields.get("title", '""'), path),
                diagram=_unescape(fields.get("diagram", '""'), path),
                line=int(fields.get("line", "0")),
                failure_modes=tuple(fm.strip() for fm in failure_modes.split(",") if fm.strip()),
            )
        )
    return package.group("name"), root_causes


def read_items(paths: list[str]) -> dict[str, Any]:
    """Items of LOBSTER files, keyed by tag (without version)."""
    mh = Message_Handler()
    items: dict[str, Any] = {}
    for path in paths:
        try:
            lobster_read(mh, path, "input", items)
        except LOBSTER_Error as e:
            raise ConversionError(f"cannot read {path}: {e}") from e
    return items


def _link_ids(need: dict[str, Any], field_name: str) -> list[str]:
    return [parse_link(v, "req").tag for v in _text_values(need, field_name)]


def fault_ids(need: dict[str, Any], known: set[str]) -> list[str]:
    """The ``fault_id`` values of a need; each one must be a known fault model ID."""
    values = [v.strip() for text in _text_values(need, "fault_id") for v in text.split(",") if v.strip()]
    if not values:
        raise ConversionError(f"{need['id']}: fault_id is missing")
    unknown = [v for v in values if v not in known]
    if unknown:
        raise ConversionError(f"{need['id']}: unknown fault_id {unknown}, expected fault model IDs {sorted(known)}")
    return values


def api_tags(need: dict[str, Any], needs: dict[str, dict[str, Any]], api_items: dict[str, Any]) -> list[Tracing_Tag]:
    """Public API methods of the ``real_arc_int_op`` needs the failure mode violates.

    An operation without a matching API method is referenced as
    ``req <interface>::<operation>``, which LOBSTER reports as unknown.
    """
    tags: list[Tracing_Tag] = []
    for op_id in _link_ids(need, "violates"):
        operation = needs.get(op_id)
        if not operation or operation.get("type") != "real_arc_int_op":
            continue
        for interface_id in _link_ids(operation, "included_by"):
            interface = needs.get(interface_id, {})
            class_name = str(interface.get("title", interface_id)).strip()
            method = str(operation.get("title", "")).strip()
            declaration = f"{class_name}::{method}"
            # Template arguments may follow the class and the method name.
            pattern = re.compile(
                rf"(?<![A-Za-z0-9_]){re.escape(class_name)}(?:<[^()]*>)?::{re.escape(method)}(?:<[^()]*>)?\("
            )
            matches = sorted(key for key, item in api_items.items() if pattern.search(item.text or ""))
            found = [api_items[key].tag for key in matches] or [Tracing_Tag("req", declaration)]
            tags.extend(tag for tag in found if tag.key() not in {t.key() for t in tags})
    return tags


def select_failure_modes(needs: dict[str, dict[str, Any]], arch_id: str) -> list[dict[str, Any]]:
    """The valid ``comp_saf_fmea`` needs violating ``arch_id``, sorted by ID."""
    selected = []
    for need_id in sorted(needs):
        need = needs[need_id]
        if need.get("type") != NEED_TYPE or arch_id not in _link_ids(need, "violates"):
            continue
        if need.get("status") == "invalid":
            logger.info("Skipping %s with status invalid", need_id)
            continue
        if not _RE_IDENTIFIER.match(need_id):
            raise ConversionError(f"{need_id}: the need ID is not a valid identifier for a fault tree")
        selected.append(need)
    return selected


def _version(need: dict[str, Any]) -> str | None:
    version = need.get("version")
    return None if version in (None, "") else str(version)


def failure_mode_item(
    need: dict[str, Any], package: str, needs: dict[str, dict[str, Any]], api_items: dict[str, Any]
) -> Requirement:
    item = Requirement(
        tag=Tracing_Tag("req", f"{package}.{need['id']}"),
        location=_location(need, need["_source"]),
        framework=FRAMEWORK,
        kind="FailureMode",
        name=f"{package}.{need['id']}",
        text=str(need.get("title") or need["id"]),
        status=None,
    )
    for tag in api_tags(need, needs, api_items):
        item.add_tracing_target(tag)
    return item


def root_cause_item(root_cause: RootCause, fta_package: str) -> Requirement:
    item = Requirement(
        tag=Tracing_Tag("req", f"{fta_package}.{root_cause.name}"),
        location=File_Reference(root_cause.diagram, line=root_cause.line if root_cause.line >= 1 else None),
        framework="PlantUML",
        kind="RootCause",
        name=f"{fta_package}.{root_cause.name}",
        text=root_cause.title,
        status=None,
    )
    for failure_mode in root_cause.failure_modes:
        item.add_tracing_target(Tracing_Tag("req", failure_mode))
    return item


def assessment_item(
    need: dict[str, Any], package: str, root_causes: list[Requirement], measures: dict[str, Any]
) -> Requirement:
    item = Requirement(
        tag=Tracing_Tag("req", f"{package}.{need['id']}.assessment", _version(need)),
        location=_location(need, need["_source"]),
        framework=FRAMEWORK,
        kind="RootCauseAssessment",
        name=f"{package}.{need['id']}.assessment",
        text=str(need.get("content") or need.get("title") or ""),
        status=None,
    )
    for root_cause in root_causes:
        item.add_tracing_target(root_cause.tag)
    for link in _text_values(need, "mitigated_by"):
        tag = parse_link(link, "req")
        if tag.key() in measures:
            item.add_tracing_target(tag)
        else:
            logger.info("%s: %s is not a measure of the analysis, not traced", need["id"], tag.key())
    return item


def _escape(text: str) -> str:
    return _RE_RST_SPECIAL.sub(r"\\\1", " ".join(text.split()))


def render_rst(
    title: str,
    failure_modes: list[dict[str, Any]],
    root_causes: dict[str, list[Requirement]],
    diagrams: list[str],
) -> str:
    """Failure modes with their root causes, then the fault-tree diagrams."""
    lines = [title, "=" * len(title), ""]
    if not failure_modes:
        lines += ["No failure modes.", ""]
    else:
        lines += [
            ".. list-table::",
            "   :header-rows: 1",
            "   :widths: 25 30 15 20 10",
            "",
            "   * - Failure mode",
            "     - Failure effect",
            "     - Fault models",
            "     - Root causes",
            "     - Sufficient",
        ]
        for need in failure_modes:
            causes = root_causes.get(need["id"], [])
            lines += [
                f"   * - **{_escape(str(need.get('title', '')))}**",
                "",
                f"       ``{need['id']}``",
                f"     - {_escape(str(need.get('failure_effect', '')))}",
                f"     - {_escape(', '.join(_text_values(need, 'fault_id')))}",
                f"     - {_escape('; '.join(rc.text or rc.name for rc in causes)) if causes else '-'}",
                f"     - {_escape(str(need.get('sufficient', '')))}",
            ]
        lines.append("")
    if diagrams:
        lines += ["Fault Trees", "-" * len("Fault Trees"), ""]
        for diagram in diagrams:
            lines += [f".. uml:: {diagram}", ""]
    return "\n".join(lines)


@dataclass
class Result:
    failure_modes: list[Requirement]
    root_causes: list[Requirement]
    assessments: list[Requirement]
    rst: str


def convert(
    needs_files: list[str],
    arch_id: str,
    package: str,
    spec_files: list[str],
    api_files: list[str],
    fta_events: str | None,
    measure_files: list[str],
    title: str = "Safety Analysis",
    diagrams: list[str] | None = None,
) -> Result:
    """Convert the FMEA needs violating ``arch_id`` and the generated fault-tree stub."""
    if not _RE_IDENTIFIER.match(package):
        raise ConversionError(f"package {package!r} is not a valid identifier")
    needs: dict[str, dict[str, Any]] = {}
    for path in needs_files:
        for need_id, need in load_needs(path).items():
            if need_id in needs:
                raise ConversionError(f"need {need_id} is defined in more than one needs.json")
            needs[need_id] = {**need, "id": need_id, "_source": path}

    known_fault_ids = load_fault_ids(spec_files)
    selected = select_failure_modes(needs, arch_id)
    for need in selected:
        fault_ids(need, known_fault_ids)
    api_items = read_items(api_files)
    fm_items = [failure_mode_item(need, package, needs, api_items) for need in selected]

    rc_items: list[Requirement] = []
    if fta_events:
        fta_package, root_causes = load_root_causes(fta_events)
        rc_items = [root_cause_item(rc, fta_package) for rc in root_causes]
    rc_by_failure_mode: dict[str, list[Requirement]] = {}
    for rc in rc_items:
        for ref in rc.unresolved_references:
            fm_id = ref.tag.split(".", 1)[1] if ref.tag.startswith(package + ".") else ref.tag
            rc_by_failure_mode.setdefault(fm_id, []).append(rc)

    measures = read_items(measure_files)
    assessments = []
    for need in selected:
        causes = rc_by_failure_mode.get(need["id"], [])
        if not causes:
            logger.info("%s: no root cause in the fault trees, no assessment", need["id"])
        elif need.get("sufficient") != "yes":
            logger.info("%s: not rated sufficient, its root causes stay unassessed", need["id"])
        else:
            assessments.append(assessment_item(need, package, causes, measures))

    if not selected:
        logger.warning("no %s need violates %s", NEED_TYPE, arch_id)
    return Result(fm_items, rc_items, assessments, render_rst(title, selected, rc_by_failure_mode, diagrams or []))


def _write(path: str, items: list[Requirement]) -> None:
    with open(path, "w", encoding="utf-8") as f:
        lobster_write(f, Requirement, GENERATOR, items)


def main(argv: list[str] | None = None) -> int:
    """Entry point of the converter."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("needs", nargs="+", help="needs.json files with the FMEA needs")
    parser.add_argument("--arch-id", required=True, help="convert the FMEA needs violating this need ID")
    parser.add_argument("--package", required=True, help="package of the failure modes the fault trees name")
    parser.add_argument("--spec", action="append", required=True, help="TRLC model (.rsl) with the Guideword enum")
    parser.add_argument("--api", action="append", default=[], help="public API .lobster file (repeatable)")
    parser.add_argument("--fta-events", help="fta_events.trlc stub generated by puml_cli from the fault trees")
    parser.add_argument("--measures", action="append", default=[], help="measure .lobster file (repeatable)")
    parser.add_argument("--diagram", action="append", default=[], help="fault-tree diagram shown on the page")
    parser.add_argument("--failuremodes-out", required=True)
    parser.add_argument("--root-causes-out", required=True)
    parser.add_argument("--assessments-out", required=True)
    parser.add_argument("--rst-out", required=True)
    parser.add_argument("--title", default="Safety Analysis", help="heading of the RST page")
    parser.add_argument("--log-level", choices=sorted(_LEVEL_MAP), default="warn", dest="log_level")
    args = parser.parse_args(argv)
    logging.basicConfig(level=_LEVEL_MAP[args.log_level], format="%(levelname)s: %(message)s")

    try:
        result = convert(
            args.needs,
            args.arch_id,
            args.package,
            args.spec,
            args.api,
            args.fta_events,
            args.measures,
            args.title,
            args.diagram,
        )
    except (ConversionError, ConfigError) as e:
        logger.error("%s", e)
        return 1
    _write(args.failuremodes_out, result.failure_modes)
    _write(args.root_causes_out, result.root_causes)
    _write(args.assessments_out, result.assessments)
    Path(args.rst_out).write_text(result.rst, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
